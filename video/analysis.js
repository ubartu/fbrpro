function parseTracking(data){
  if(data?.version!=="fbrpro-video-tracking-v1"||!Array.isArray(data.frames)||
     !positive(data.coordinate_length_m)||!positive(data.coordinate_width_m))
    throw Error("Choose an fbrpro tracking JSON with pitch dimensions and frames.");
  if(data.frames.some(f=>!f||!validMs(f.video_time_ms)||!Array.isArray(f.objects)))
    throw Error("The tracking report contains an invalid frame.");
  for(const f of data.frames){
    if(f.objects.some(o=>!o||typeof o.track_id!=="string"||typeof o.object_type!=="string"||
      (o.x_m!=null&&!finite(o.x_m))||(o.y_m!=null&&!finite(o.y_m))))
      throw Error("The tracking report contains an invalid object.");
  }
  const frames=[...data.frames].sort((a,b)=>a.video_time_ms-b.video_time_ms);
  const gaps=[];
  for(let i=1;i<frames.length;i++){
    const g=frames[i].video_time_ms-frames[i-1].video_time_ms;
    if(g>0&&g<=5000&&frames[i].clip_id===frames[i-1].clip_id)gaps.push(g);
  }
  gaps.sort((a,b)=>a-b);
  // Avoid showing a stale position when playback crosses an untracked window.
  const gap=positive(data.sample_fps)?1000/data.sample_fps:gaps[Math.floor(gaps.length/2)]||350;
  const tolerance=Math.min(1250,Math.max(150,gap*.7));
  return {...data,frames,tolerance};
}
function parseMetrics(data){
  if(data?.version!=="fbrpro-video-metrics-v1"||!Array.isArray(data.players))
    throw Error("Choose a movement metrics report generated by fbrpro.");
  if(data.match_ids!==undefined&&(!Array.isArray(data.match_ids)||data.match_ids.some(id=>typeof id!=="string")))
    throw Error("The movement report contains invalid match IDs.");
  const validPlayers=players=>Array.isArray(players)&&players.every(p=>p&&
    typeof p.player_id==="string"&&Array.isArray(p.measures)&&
    p.measures.every(m=>m&&typeof m.metric==="string"&&Array.isArray(m.observations)));
  if(!validPlayers(data.players))
    throw Error("The movement report contains an invalid player or measure.");
  if(data.position_groups!==undefined&&(!Array.isArray(data.position_groups)||
     data.position_groups.some(g=>!g||typeof g.position_group!=="string"||!validPlayers(g.players))))
    throw Error("The movement report contains an invalid position group.");
  return data;
}
function nearestFrame(frames,ms){
  let low=0,high=frames.length;
  while(low<high){const mid=(low+high)>>>1;if(frames[mid].video_time_ms<ms)low=mid+1;else high=mid;}
  const before=frames[low-1],after=frames[low];
  if(!before)return after;
  if(!after)return before;
  return ms-before.video_time_ms<=after.video_time_ms-ms?before:after;
}
function probableKeeper(o){
  return o.inferred_role==="probable_goalkeeper";
}
function teamColour(o){
  return o.object_type==="ball"?"#fff180":teamColours.get(o.team_id)||
    (probableKeeper(o)?"#d6baff":inferredTeams.get(o.inferred_team)?.colour||"#e1ae5e");
}
function markerLabel(o, name){
  if(o.object_type==="ball")return "Ball";
  const group=inferredTeams.get(o.inferred_team);
  const labels=[name||o.player_id||o.track_id];
  if(group&&!o.team_id)labels.push(group.letter);
  if(probableKeeper(o))labels.push("GK?");
  return labels.join(" · ");
}
function configureInferenceLegend(shot){
  if(inferenceShot===shot)return;
  inferenceShot=shot;
  const entries=[...(shot?.groups||[])].sort().slice(0,2);
  inferredTeams=new Map(entries.map((key,i)=>{
    const letter=key==="kit:team_a"?"A":key==="kit:team_b"?"B":i===0?"A":"B";
    const colour=letter==="A"?"#7ad8f6":"#ff99bd";
    const inferred=/^kit:team_[ab]$/.test(key);
    const name=inferred?"Team "+letter:key.slice(4).replaceAll("_"," ");
    return [key,{letter,colour,name,title:inferred?name:"Kit "+letter+" · "+name,inferred}];
  }));
  for(const letter of ["a","b"]){
    const group=[...inferredTeams.values()].find(g=>g.letter.toLowerCase()===letter);
    $("legend-kit-"+letter).hidden=!group;
    if(group)$("label-kit-"+letter).textContent=group.title;
  }
  $("legend-gk").hidden=!shot?.keeper;
  $("inference-hint").hidden=!shot;
  if(shot)$("inference-hint").textContent=entries.length||shot.keeper
    ?"Shirt groups and goalkeeper markers are estimates. Confirm team and player identities separately."
    :"Team groups need clear, repeated views of both kits in the same shot.";
}
function pitchPolygon(frame){
  const points=frame.pitch_boundary?.polygon_xy;
  if(frame.pitch_boundary_status==="unavailable"||!Array.isArray(points)||points.length<3||
     !points.every(p=>Array.isArray(p)&&p.length===2&&p.every(finite)))return;
  return points;
}
function pitchBoundaryVerified(frame){
  return frame.pitch_boundary?.source==="verified_calibration";
}
function summarizeCandidates(frame,polygon){
  const parts=[];
  if(validMs(frame.person_candidates))parts.push(fmt(frame.person_candidates)+" person candidate"+(frame.person_candidates===1?"":"s"));
  if(validMs(frame.off_pitch_candidates))parts.push(fmt(frame.off_pitch_candidates)+" rejected outside pitch");
  if(validMs(frame.pitch_unavailable_candidates))parts.push(fmt(frame.pitch_unavailable_candidates)+" withheld for missing outline");
  status("candidate-status",parts.join(" · "));
  const boundary=polygon?(pitchBoundaryVerified(frame)?"Pitch outline · Verified camera calibration":
    frame.pitch_boundary?.source==="automatic_landmarks"?"Pitch outline · Automatic landmark estimate":"Pitch outline · Estimated from footage"):
    "pitch_boundary_status" in frame||"pitch_boundary" in frame?"Pitch outline unavailable in this frame.":"";
  status("boundary-status",boundary);
}
