function phaseName(value){
  return value==="regain_candidate"?"Team regain candidate":
    value==="opposition_build_up_sample"?"Opposition build-up sample":reason[value]||value||"Selected moment";
}
function renderPhase(ms){
  const active=getMismatch(tracking,clipPlan)?null:clipPlan?.clips.find(
    c=>c.video_start_ms<=ms&&ms<=c.video_end_ms);
  const phases=active?.opportunities.filter(o=>o.video_start_ms<=ms&&ms<=o.video_end_ms)
    .map(o=>phaseName(o.reason));
  const message=active?[active.id,"Half "+active.period,...new Set(phases)].join(" · "):
    $("clip-markers").hidden?"":"Selected clips are marked on the timeline.";
  const phase=$("phase-now");
  if(phase.textContent!==message)phase.textContent=message;
}
function renderClipMarkers(min,max){
  const markers=$("clip-markers");
  markers.replaceChildren();
  const clips=clipPlan?.clips||tracking?.clips||[];
  if(max<=min||getMismatch(tracking,clipPlan)){markers.hidden=true;return;}
  for(const c of clips){
    if(!validMs(c.video_start_ms)||!validMs(c.video_end_ms))continue;
    const start=Math.max(min,c.video_start_ms),end=Math.min(max,c.video_end_ms);
    if(start>=end)continue;
    const marker=node("button");
    marker.type="button";
    marker.style.left=(start-min)/(max-min)*100+"%";
    marker.style.width=(end-start)/(max-min)*100+"%";
    const phases=[...new Set((c.opportunities||[]).map(o=>phaseName(o.reason)))];
    marker.title=[c.id||c.clip_id,clock(c.video_start_ms),...phases].join(" · ");
    marker.setAttribute("aria-label","Jump to "+marker.title);
    marker.onclick=()=>seek(start);
    markers.append(marker);
  }
  markers.hidden=!markers.childElementCount;
}
function renderFrame(){
  scheduledFrame=0;
  const hasVideo=Number.isFinite(video.duration);
  const ms=hasVideo?video.currentTime*1000:replayMs;
  $("video-clock").textContent=clock(hasVideo?ms:0);
  $("replay-time").textContent=clock(ms);
  if(!$("timeline").disabled)$("timeline").value=String(Math.round(ms));
  renderPhase(ms);
  if(!tracking)return;
  const frame=nearestFrame(tracking.frames,ms);
  const mismatch=getMismatch(tracking,clipPlan);
  const usable=frame&&!mismatch&&Math.abs(frame.video_time_ms-ms)<=tracking.tolerance;
  let message;
  if(!tracking.frames.length)message="The tracking report has no sampled frames.";
  else if(mismatch)message="Tracking is hidden until the clip plan matches the tracking report.";
  else if(!usable)message="No tracking sample at this time. Seek to a tracked clip.";
  if(!usable){
    if(lastFrame!==undefined){pitchLayer.replaceChildren();footageLayer.replaceChildren();}
    lastFrame=undefined;
    if(!$("identity-panel").hidden)showIdentityTracks();
    if(lastMessage!==message)status("tracking-status",message);
    lastMessage=message;
    return;
  }
  if(frame===lastFrame)return;
  lastFrame=frame;
  if(!$("identity-panel").hidden)showIdentityTracks(frame);
  drawBoxes(frame);
  const frag=document.createDocumentFragment();
  let plotted=0, missing=0, uncalibrated=0, unidentified=0;
  const length=tracking.coordinate_length_m,width=tracking.coordinate_width_m;
  for(const o of frame.objects){
    if(o.visibility==="missing"||!o.observed||o.estimated){missing++;continue;}
    if(!finite(o.x_m)||!finite(o.y_m)||o.x_m<0||o.x_m>length||o.y_m<0||o.y_m>width){uncalibrated++;continue;}
    plotted++;
    if(o.object_type==="player"&&!o.player_id)unidentified++;
    const x=o.x_m/length*100,y=o.y_m/width*64;
    const ball=o.object_type==="ball";
    const group=svg("g",{});
    const circle=svg("circle",{cx:x,cy:y,r:ball?1.05:1.52,fill:teamColour(o),stroke:"#103226","stroke-width":".34"});
    const title=svg("title",{});title.textContent=(o.player_id||o.track_id)+(o.team_id?" · "+o.team_id:" · team unknown");
    circle.append(title);group.append(circle);
    if(!ball){
      const t=svg("text",{x,y:y-2.0,"text-anchor":"middle",fill:"#f6fff6","font-size":"1.8","font-weight":"650","paint-order":"stroke",stroke:"#15392b","stroke-width":".32"});
      const name=clipPlan?.players?.find(p=>p.id===o.player_id)?.name;
      t.textContent=name||o.player_id||o.track_id;
      group.append(t);
    }
    frag.append(group);
  }
  pitchLayer.replaceChildren(frag);
  message=[plotted+" plotted",unidentified+" unidentified people",missing+" not visible",uncalibrated+" without a pitch position"].join(" · ");
  if(frame.calibration_status==="uncalibrated")message+=" · Pitch calibration unavailable";
  if(frame.calibration_status==="unverified")message+=" · Pitch calibration unverified";
  if(!frame.objects.some(o=>o.object_type==="ball"&&o.observed))message+=" · Ball unavailable";
  if(frame.camera_cut_suspected)message+=" · Possible camera cut";
  if(lastMessage!==message)status("tracking-status",message);
  lastMessage=message;
}
function queueFrame(){
  if(!scheduledFrame)scheduledFrame=requestAnimationFrame(renderFrame);
}
function configureTimeline(){
  const hasVideo=Number.isFinite(video.duration);
  const frames=tracking?.frames;
  const min=hasVideo?0:frames?.[0]?.video_time_ms??0;
  const max=hasVideo?Math.round(video.duration*1000):frames?.[frames.length-1]?.video_time_ms??min;
  const timeline=$("timeline");
  timeline.disabled=max<=min;
  timeline.min=String(min);
  timeline.max=String(max);
  timeline.value=String(hasVideo?Math.round(video.currentTime*1000):replayMs);
  renderClipMarkers(min,max);
  $("first-sample").hidden=!frames?.length||Boolean(getMismatch(tracking,clipPlan));
  queueFrame();
}
function seek(ms){
  if(!validMs(ms))return;
  if(Number.isFinite(video.duration)){
    if(ms>video.duration*1000+1){
      status("video-status","The evidence time is outside the open video. Check that the files match.",true);
      return;
    }
    video.currentTime=ms/1000;
  }else replayMs=ms;
  queueFrame();
}
