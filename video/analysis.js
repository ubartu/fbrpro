const states={observed:"Observed",not_observed:"Visible but not observed",unobservable:"Unobservable",partial:"Partial coverage"};
const groupNames={defensive:"Defensive midfield",central:"Central midfield",attacking:"Attacking midfield"};
function evidencePicker(controls,id,name,entries,value,onChange){
  const label=node("label",null,name);
  const select=node("select");
  select.id=id;
  for(const [key,display] of entries)option(select,key,display);
  select.value=String(value);
  select.onchange=()=>{onChange(select.value);renderMetrics();$(id)?.focus();};
  label.append(select);controls.append(label);
}
function renderMetrics(){
  const cards=$("metric-cards");
  cards.replaceChildren();
  if(!metrics)return;
  const pooled=metrics.analysis_scope==="selected_clips_across_matches";
  const mismatch=getMismatch(metrics,tracking)||getMismatch(metrics,clipPlan)||
    (pooled&&getMismatch(tracking,clipPlan));
  $("evidence-scope").textContent=pooled?fmt(metrics.match_ids?.length)+" matches":
    metrics.analysis_scope==="selected_clips"?"Selected clips":"Report scope";
  status("metrics-status",mismatch
    ?"File "+mismatch+" differ. Evidence seeking is disabled until the files match."
    :metrics.players.length?metrics.players.length+" players · "+
      (pooled?"Evidence pooled from selected clips across matches.":"Movement measured in selected clips"+(metrics.match_id?" · Match "+metrics.match_id:"")+".")
    :"No player measures in this report.",Boolean(mismatch));
  if(!metrics.players.length)return;
  const controls=node("div","metric-picker");
  const groups=metrics.position_groups?.filter(g=>g.players.length)||[];
  if(groups.length){
    const choices=[["","All players"],...groups.map(g=>[g.position_group,groupNames[g.position_group]||g.position_group])];
    evidencePicker(controls,"metric-group","Position group",choices,metricGroup,
      value=>{metricGroup=value;metricPlayer=0;});
  }
  const players=groups.find(g=>g.position_group===metricGroup)?.players||metrics.players;
  evidencePicker(controls,"metric-player","Player",players.map((p,i)=>[String(i),p.name||p.player_id]),
    metricPlayer,value=>{metricPlayer=Number(value);});
  cards.append(controls);
  const player=players[metricPlayer];
  if(!player?.measures.length){
    cards.append(node("p","hint","No movement measures for this player."));return;
  }
  for(const m of player.measures){
    const card=node("article","metric-card");
    card.append(node("h3",null,m.label||m.metric));
    card.append(node("p","metric-value",finite(m.per_100)?fmt(m.per_100)+" / 100":"No evidence"));
    const totals=m.unit==="ms"
      ?secs(m.numerator)+" / "+secs(m.denominator)+" observed"
      :fmt(m.numerator)+" / "+fmt(m.denominator)+" opportunities";
    if(finite(m.numerator)&&finite(m.denominator))
      card.append(node("small",null,m.denominator>0?totals:"No observable opportunities"));
    card.append(node("small",null,(finite(m.coverage_pct)?fmt(m.coverage_pct)+"% coverage":"Coverage unavailable")+" · "+fmt(m.excluded)+" excluded"));
    const peer=m.comparison;
    if(metricGroup&&peer){
      card.append(node("small","peer-comparison","Peers’ rates · "+fmt(peer.higher)+" higher · "+
        fmt(peer.tied)+" tied · "+fmt(peer.lower)+" lower · "+fmt(peer.missing)+" unavailable"));
    }
    if(m.observations.length){
      const details=node("details","metric-evidence");
      details.append(node("summary",null,"Review "+m.observations.length+" observations"));
      // Create evidence controls only when requested; larger reports remain quick to open.
      details.addEventListener("toggle",()=>{
        if(!details.open||details.dataset.ready)return;
        details.dataset.ready="true";
        for(const o of m.observations){
          if(!o)continue;
          const row=node("div","evidence-row");
          row.append(node("small",null,[
            pooled&&o.match_id?"Match "+o.match_id:"",
            o.clip_id||"Clip",states[o.status]||"Observation",
            validMs(o.video_start_ms)?clock(o.video_start_ms):"",
          ].filter(Boolean).join(" · ")));
          if(o.reason)row.append(node("small",null,o.reason));
          const active=tracking||clipPlan;
          const matched=!pooled||(o.match_id===active?.match_id&&o.video_id===active?.video_id&&
            o.plan_id===active?.plan_id&&Boolean(o.plan_id));
          const button=node("button","secondary",matched?"Jump to evidence":"Load this clip’s files to seek");
          button.type="button";button.disabled=!matched||Boolean(mismatch)||!validMs(o.video_start_ms)||
            (!Number.isFinite(video.duration)&&!tracking?.frames.length);
          button.onclick=()=>seek(o.video_start_ms);
          row.append(button);details.append(row);
        }
      });
      card.append(details);
    }
    cards.append(card);
  }
}
