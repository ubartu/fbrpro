function node(tag, cls, content){
  const el=document.createElement(tag);
  if(cls)el.className=cls;
  if(content!==undefined)el.textContent=content;
  return el;
}
function svg(tag, attrs){
  const el=document.createElementNS(SVG,tag);
  for(const [k,v] of Object.entries(attrs))el.setAttribute(k,v);
  return el;
}
function clock(ms){
  if(!finite(ms))return "00:00.0";
  const t=Math.max(0,Math.floor(ms/100));
  const h=Math.floor(t/36000), m=Math.floor(t/600)%60;
  const s=Math.floor(t/10)%60;
  return (h?h+":":"")+String(m).padStart(2,"0")+":"+String(s).padStart(2,"0")+"."+(t%10);
}
function getMismatch(a,b){
  if(!a||!b)return "";
  if(a.match_id&&b.match_id&&a.match_id!==b.match_id)return "match IDs";
  if(a.video_id&&b.video_id&&a.video_id!==b.video_id)return "video IDs";
  if(a.plan_id&&b.plan_id&&a.plan_id!==b.plan_id)return "clip-plan IDs";
  return "";
}
function showSession(){
  const pairs=[[tracking,clipPlan,"Tracking and clip plan"],[metrics,clipPlan,"Movement report and clip plan"],[metrics,tracking,"Movement report and tracking"]];
  const warnings=pairs.map(([a,b,what])=>{
    const mismatch=getMismatch(a,b);
    return mismatch?what+" have different "+mismatch+". Load matching files before reviewing their evidence together.":"";
  }).filter(Boolean);
  if(metrics?.match_ids&&tracking&&!metrics.match_ids.includes(tracking.match_id))
    warnings.push("The open tracking match is outside this movement report.");
  if(tracking?.sync?.length&&tracking.sync.every(s=>s.status!=="verified"))
    warnings.push("This replay uses video time. The match clock has no verified alignment.");
  $("session-status").hidden=!warnings.length;
  $("session-status").textContent=warnings.join(" ");
  const report=clipPlan||tracking||metrics;
  if(report?.match_id)$("session-summary").textContent="Match "+report.match_id+" · "+[
    report.video_id?"Video "+report.video_id:"",
    Array.isArray(clipPlan?.clips)?clipPlan.clips.length+" selected clips":"",
    "Files stay on this device",
  ].filter(Boolean).join(" · ");
  else if(report?.match_ids?.length)$("session-summary").textContent=report.match_ids.length+" matches · Files stay on this device";
}
function parseTracking(data){
  if(data?.version!=="fbrpro-video-tracking-v1"||!Array.isArray(data.frames)||
     !positive(data.coordinate_length_m)||!positive(data.coordinate_width_m))
    throw Error("Choose an fbrpro tracking JSON with pitch dimensions and frames.");
  if(data.frames.some(f=>!f||!validMs(f.video_time_ms)||!Array.isArray(f.objects)))
    throw Error("The tracking report contains an invalid frame.");
  for(const f of data.frames){
    if(f.objects.some(o=>!o||typeof o.track_id!=="string"||typeof o.object_type!=="string"||
      (o.x_m!=null&&!finite(o.x_m))||(o.y_m!=null&&!finite(o.y_m))))
      throw Error("The tracking report contains an invalid object.");
  }
  const frames=[...data.frames].sort((a,b)=>a.video_time_ms-b.video_time_ms);
  const gaps=[];
  for(let i=1;i<frames.length;i++){
    const g=frames[i].video_time_ms-frames[i-1].video_time_ms;
    if(g>0&&g<=5000&&frames[i].clip_id===frames[i-1].clip_id)gaps.push(g);
  }
  gaps.sort((a,b)=>a-b);
  // Avoid showing a stale position when playback crosses an untracked window.
  const gap=positive(data.sample_fps)?1000/data.sample_fps:gaps[Math.floor(gaps.length/2)]||350;
  const tolerance=Math.min(1250,Math.max(150,gap*.7));
  return {...data,frames,tolerance};
}
function parseMetrics(data){
  if(data?.version!=="fbrpro-video-metrics-v1"||!Array.isArray(data.players))
    throw Error("Choose a movement metrics report generated by fbrpro.");
  if(data.match_ids!==undefined&&(!Array.isArray(data.match_ids)||data.match_ids.some(id=>typeof id!=="string")))
    throw Error("The movement report contains invalid match IDs.");
  const validPlayers=players=>Array.isArray(players)&&players.every(p=>p&&
    typeof p.player_id==="string"&&Array.isArray(p.measures)&&
    p.measures.every(m=>m&&typeof m.metric==="string"&&Array.isArray(m.observations)));
  if(!validPlayers(data.players))
    throw Error("The movement report contains an invalid player or measure.");
  if(data.position_groups!==undefined&&(!Array.isArray(data.position_groups)||
     data.position_groups.some(g=>!g||typeof g.position_group!=="string"||!validPlayers(g.players))))
    throw Error("The movement report contains an invalid position group.");
  return data;
}
function nearestFrame(frames,ms){
  let low=0,high=frames.length;
  while(low<high){const mid=(low+high)>>>1;if(frames[mid].video_time_ms<ms)low=mid+1;else high=mid;}
  const before=frames[low-1],after=frames[low];
  if(!before)return after;
  if(!after)return before;
  return ms-before.video_time_ms<=after.video_time_ms-ms?before:after;
}
function teamColour(o){
  return o.object_type==="ball"?"#fff9e7":teamColours.get(o.team_id)||"#e1ae5e";
}
function showOverlayControl(){
  const fits=positive(tracking?.frame_width)&&positive(tracking?.frame_height)&&
    positive(video.videoWidth)&&positive(video.videoHeight)&&
    Math.abs((video.videoWidth/video.videoHeight)/(tracking.frame_width/tracking.frame_height)-1)<.01;
  $("overlay-control").hidden=!fits||Boolean(getMismatch(tracking,clipPlan));
  footageLayer.toggleAttribute("hidden",$("overlay-control").hidden||!$("show-boxes").checked);
  if(fits)footageLayer.setAttribute("viewBox","0 0 "+tracking.frame_width+" "+tracking.frame_height);
}
function drawBoxes(frame){
  if(footageLayer.hasAttribute("hidden"))return;
  const frag=document.createDocumentFragment();
  for(const o of frame.objects){
    const b=o.bbox_xyxy;
    if(!o.observed||o.estimated||o.visibility==="missing"||!Array.isArray(b)||b.length!==4||!b.every(finite))continue;
    const [x,y,right,bottom]=b;
    if(right<=x||bottom<=y)continue;
    const fill=teamColour(o);
    frag.append(svg("rect",{x,y,width:right-x,height:bottom-y,fill:"none",stroke:fill,"stroke-width":1.4,
      "vector-effect":"non-scaling-stroke"}));
    const t=svg("text",{x,y:Math.max(10,y-4),fill,stroke:"#15392b","stroke-width":"2",
      "paint-order":"stroke","font-size":tracking.frame_width*.012,"font-weight":"700"});
    t.textContent=o.object_type==="ball"?"Ball":o.player_id||o.track_id;
    frag.append(t);
  }
  footageLayer.replaceChildren(frag);
}
